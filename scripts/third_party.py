def metadata(target):
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked",
         "--filter-platform", target],
        cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return json.loads(out)


def shipped(meta):
    """Ids of the packages pd-app depends on at run time, not counting
    the workspace's own crates."""
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    workspace = set(meta["workspace_members"])
    app = next(p["id"] for p in meta["packages"] if p["name"] == APP)
    seen, todo = set(), [app]
    while todo:
        for dep in nodes[todo.pop()]["deps"]:
            normal = any(k["kind"] is None for k in dep["dep_kinds"])
            if normal and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                todo.append(dep["pkg"])
    return seen - workspace


def licence_texts(manifest):
    folder = os.path.dirname(manifest)
    texts = []
    for name in sorted(os.listdir(folder)):
        path = os.path.join(folder, name)
        if os.path.isfile(path) and name.lower().startswith(LICENSE_FILES):
            with open(path, encoding="utf-8", errors="replace") as f:
                texts.append((name, f.read().strip()))
    return texts


def build():
    packages = {}
    for target in TARGETS:
        meta = metadata(target)
        by_id = {p["id"]: p for p in meta["packages"]}
        for pid in shipped(meta):
            p = by_id[pid]
            packages[(p["name"], p["version"])] = p
    crates = sorted(packages.values(), key=lambda p: (p["name"].lower(), p["version"]))

    texts = {}  # hash -> (text, [crate names])
    files = {p["id"]: licence_texts(p["manifest_path"]) for p in crates}
    for p in crates:
        for name, text in files[p["id"]]:
            h = hashlib.sha256(text.encode()).hexdigest()[:12]
            texts.setdefault(h, (text, []))[1].append(f'{p["name"]} {p["version"]} ({name})')

    # The Apache-2.0 text most crates ship, for those that ship none.
    apache = max(
        (t for t in texts.values() if t[0].lstrip().startswith("Apache License")),
        key=lambda t: len(t[1]))[0]
    standard = {"MIT": MIT, "Apache-2.0": apache, "Zlib": ZLIB, "BSL-1.0": BSL}
    used_standard = set()

    rows = []
    for p in crates:
        refs = []
        for name, text in files[p["id"]]:
            h = hashlib.sha256(text.encode()).hexdigest()[:12]
            refs.append(f'<a href="#t{h}">{html.escape(name)}</a>')
        if not refs:
            ids = re.findall(r"[A-Za-z0-9.+-]+", p.get("license") or "")
            ids = [i for i in ids if i not in ("OR", "AND", "WITH")]
            missing = [i for i in ids if i not in standard]
            if missing or not ids:
                sys.exit(f'{p["name"]}: no licence file, and no standard text for {missing or "it"}')
            used_standard.update(ids)
            who = ", ".join(p.get("authors") or []) or "the authors"
            where = p.get("repository") or ""
            refs.append(", ".join(f'<a href="#std-{i}">{i}</a>' for i in ids)
                        + f' (standard text; copyright {html.escape(who)}'
                        + (f', <a href="{html.escape(where)}">{html.escape(where)}</a>' if where else "")
                        + ")")
        rows.append(
            f'<tr><td>{html.escape(p["name"])}</td><td>{html.escape(p["version"])}</td>'
            f'<td>{html.escape(p.get("license") or "see files")}</td>'
            f'<td>{"; ".join(refs)}</td></tr>')

    font = open(os.path.join(ROOT, "assets", "fonts", "NotoSans-OFL.txt"),
                encoding="utf-8").read().strip()
    sections = []
    for h, (text, users) in sorted(texts.items(), key=lambda kv: kv[1][1][0].lower()):
        sections.append(
            f'<section id="t{h}"><h3>{html.escape(users[0])}'
            f'{f" and {len(users) - 1} more" if len(users) > 1 else ""}</h3>'
            f'<p class="users">{html.escape(", ".join(users))}</p>'
            f'<pre>{html.escape(text)}</pre></section>')

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>PathwayDesigner: third-party licences</title>
<style>
body {{ font: 14px/1.45 sans-serif; color: #1A1A1A; background: #F8F9FA;
       max-width: 960px; margin: 0 auto; padding: 16px; }}
table {{ border-collapse: collapse; width: 100%; background: #FFF; }}
th, td {{ text-align: left; padding: 3px 8px; border-bottom: 1px solid #E2E5E8; }}
pre {{ white-space: pre-wrap; background: #FFF; border: 1px solid #E2E5E8;
       padding: 8px; font-size: 12px; }}
.users {{ color: #555; font-size: 12px; }}
</style>
</head>
<body>
<h1>Third-party licences</h1>
<p>PathwayDesigner is MIT-licensed. It is built from the {len(crates)} open-source
Rust crates listed below, and uses the Noto Sans font. Their licences and
licence texts follow. This file is generated by <code>scripts/third_party.py</code>.</p>
<h2>Font</h2>
<p>Noto Sans, under the SIL Open Font Licence 1.1:</p>
<pre>{html.escape(font)}</pre>
<h2>Crates</h2>
<table>
<tr><th>Crate</th><th>Version</th><th>Licence</th><th>Licence files</th></tr>
{chr(10).join(rows)}
</table>
<h2>Licence texts</h2>
{chr(10).join(sections)}
<h2>Standard licence texts</h2>
<p>For crates that ship no licence file of their own.</p>
{chr(10).join(f'<section id="std-{i}"><h3>{i}</h3><pre>{html.escape(standard[i])}</pre></section>' for i in sorted(used_standard))}
</body>
</html>
"""


def main():
    page = build()
    if "--check" in sys.argv:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != page:
            print("THIRD-PARTY.html is out of date: run python scripts/third_party.py")
            sys.exit(1)
        print("THIRD-PARTY.html is up to date")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(page)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
