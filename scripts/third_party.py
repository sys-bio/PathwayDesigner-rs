"""Writes THIRD-PARTY.html: every crate the app is built from, with its licence
and licence texts, and the bundled font (SPEC-Rust §8.5). The web app ships the
file next to itself, and the About box links to it.

    python scripts/third_party.py           # write THIRD-PARTY.html
    python scripts/third_party.py --check   # fail if it is out of date (CI)

The crates are pd-app's normal dependencies, for the browser and for the
desktop. Build-time dependencies are left out: nothing of them ends up in the
app. Licence texts are the LICENSE, COPYING and NOTICE files each crate ships;
identical texts are listed once.
"""
