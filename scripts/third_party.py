OUT = os.path.join(ROOT, "THIRD-PARTY.html")
APP = "pd-app"
TARGETS = ["wasm32-unknown-unknown", "x86_64-unknown-linux-gnu",
           "x86_64-pc-windows-msvc", "aarch64-apple-darwin"]
LICENSE_FILES = ("license", "licence", "copying", "notice")

